// Copies the pure rule files the server must enforce (moderation, posts, handles, social links, terms version)
// from src/lib into supabase/functions/_shared/rules, so the Edge Functions run exactly the client's rules.
// Edge Functions are bundled from supabase/functions only, hence a copy. A Jest test fails when they drift.
//   node scripts/sync-shared.mjs          write the copies
//   node scripts/sync-shared.mjs --check  exit 1 if a copy is stale
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const SHARED = ["moderation", "posts", "auth", "socialLinks", "contact"];
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "supabase/functions/_shared/rules");
export const header = (name) => `// Generated by scripts/sync-shared.mjs from src/lib/${name}.ts. Edit that file, then run the script.\n`;

const check = process.argv.includes("--check");
mkdirSync(out, { recursive: true });
let stale = [];
for (const name of SHARED) {
  const want = header(name) + readFileSync(join(root, "src/lib", `${name}.ts`), "utf8");
  const file = join(out, `${name}.ts`);
  if (check) {
    if (!existsSync(file) || readFileSync(file, "utf8") !== want) stale.push(name);
  } else writeFileSync(file, want);
}
if (stale.length) {
  console.error(`Stale server rules: ${stale.join(", ")}. Run node scripts/sync-shared.mjs`);
  process.exit(1);
}
