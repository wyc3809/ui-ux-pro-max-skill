/** @jest-environment node */
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { buyouts, launches, prompts } from "../../src/data/marketplace";
import { creators, templates } from "../../src/data/mock";

/**
 * supabase/seed.sql is generated from the app's fictional demo data (src/data), so a fresh Supabase project
 * shows the same catalogue as the demo build. `supabase db reset` loads it. This test fails when the file is
 * stale; regenerate with:  WRITE_SEED=1 npx jest supabase/tests/seed
 */
const SEED = join(__dirname, "../seed.sql");

/** Stable fake account ids per demo handle (never a real person). */
export const demoUserId = (handle: string) => {
  const h = createHash("md5").update(`appseed-demo:${handle}`).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-8${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const json = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;
const cents = (hkd: number) => Math.round(hkd * 100);

export function buildSeed(): string {
  const handles = [...new Set([...creators.map((c) => c.handle), ...templates.map((t) => t.creator), ...prompts.map((p) => p.creator), ...launches.map((l) => l.maker), ...buyouts.map((b) => b.seller)])];
  const lines: string[] = [
    "-- Generated by supabase/tests/seed.test.ts from src/data (fictional demo data). Do not edit by hand.",
    "-- Regenerate: WRITE_SEED=1 npx jest supabase/tests/seed",
    "",
    `insert into auth.users (id) values\n${handles.map((h) => `  (${q(demoUserId(h))})`).join(",\n")}\non conflict do nothing;`,
    "",
  ];
  for (const h of handles) {
    const c = creators.find((x) => x.handle === h);
    lines.push(
      `insert into public.profiles (id, handle, name, bio, links, avatar_hue, terms_version) values (${q(demoUserId(h))}, ${q(h)}, ${q(c?.name ?? h)}, ${q(c?.bio ?? "")}, ${json(c?.links ?? {})}, ${c?.avatarHue ?? 262}, 999) on conflict do nothing;`,
    );
  }
  lines.push("");
  const listing = (slug: string, kind: string, owner: string, price: number, data: object) =>
    `insert into public.listings (slug, kind, owner_id, status, price, data, attested_at) values (${q(slug)}, ${q(kind)}, ${q(demoUserId(owner))}, 'live', ${price}, ${json(data)}, now()) on conflict do nothing;`;
  const priceRow = (slug: string, owner: string, price: number) =>
    `insert into public.listing_prices (listing_id, seller_id, product_id, price) values (${q(slug)}, ${q(demoUserId(owner))}, ${q(`tier_${price / 100}`)}, ${price}) on conflict do nothing;`;

  for (const t of templates) {
    lines.push(listing(t.slug, "template", t.creator, cents(t.price), t));
    if (t.price > 0) lines.push(priceRow(t.slug, t.creator, cents(t.price)));
  }
  for (const p of prompts) {
    // The full prompt lives in prompt_texts (owners only); the public row keeps the preview lines and count.
    const lines_ = p.text.split("\n");
    // Free prompts are public in full, like the demo server.
    const text = p.price === 0 ? p.text : lines_.slice(0, p.previewLines).join("\n");
    lines.push(listing(p.slug, "prompt", p.creator, cents(p.price), { ...p, text, lineCount: lines_.length }));
    lines.push(`insert into public.prompt_texts (slug, text) values (${q(p.slug)}, ${q(p.text)}) on conflict do nothing;`);
    if (p.price > 0) lines.push(priceRow(p.slug, p.creator, cents(p.price)));
  }
  for (const l of launches) lines.push(listing(l.slug, "launch", l.maker, 0, l));
  for (const b of buyouts) lines.push(listing(b.slug, "buyout", b.seller, 0, b));
  return lines.join("\n") + "\n";
}

describe("demo seed", () => {
  it("matches the demo data (regenerate with WRITE_SEED=1)", () => {
    const want = buildSeed();
    if (process.env.WRITE_SEED) writeFileSync(SEED, want);
    expect(existsSync(SEED) ? readFileSync(SEED, "utf8") : "").toBe(want);
  });

  it("never seeds a paid prompt's full text into the public row", () => {
    for (const p of prompts.filter((x) => x.price > 0 && x.text.split("\n").length > x.previewLines)) {
      const row = buildSeed().split("\n").find((l) => l.startsWith("insert into public.listings") && l.includes(`'${p.slug}'`))!;
      expect(row).not.toContain(JSON.stringify(p.text).slice(1, -1));
    }
  });
});
